def _run(par, text, size, bold=False, color=INK):
    r = par.add_run()
    r.text = text
    r.font.size, r.font.bold, r.font.name = Pt(size), bold, FONT
    r.font.color.rgb = color
    return r


def text(slide, x, y, w, h, lines, size=18, color=INK, bold=False, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP, gap=6):
    """lines: строка или список; элемент-кортеж (текст, {size, bold, color}) задаёт стиль строки."""
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = box.text_frame
    tf.word_wrap, tf.vertical_anchor = True, anchor
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = Emu(0)
    for i, line in enumerate([lines] if isinstance(lines, (str, tuple)) else lines):
        body, st = line if isinstance(line, tuple) else (line, {})
        par = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        par.alignment = align
        par.space_after = Pt(gap)
        _run(par, body, st.get("size", size), st.get("bold", bold), st.get("color", color))
    return box


