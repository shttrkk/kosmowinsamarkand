def stat(slide, x, y, w, value, label, size=40):
    """Крупное число с подписью."""
    text(slide, x, y, w, 0.75, value, size=size, bold=True, color=ACCENT)
    text(slide, x, y + size / 72 + 0.22, w, 0.9, label, size=13, color=MUTED, gap=2)


def picture(slide, name, x, y, w, h, caption=None):
    """Вписывает рисунок в рамку (x, y, w, h) с сохранением пропорций; подпись-вывод — под рамкой."""
    from PIL import Image

    path = FIG / name
    iw, ih = Image.open(path).size
    scale = min(w / iw, h / ih)
    pw, ph = iw * scale, ih * scale
    slide.shapes.add_picture(str(path), Inches(x + (w - pw) / 2), Inches(y + (h - ph) / 2), Inches(pw), Inches(ph))
    if caption:
        text(slide, x, y + h + 0.08, w, 0.5, caption, size=12, color=MUTED)


def pending(slide, x, y, w, h, key, what):
    """Явная заглушка: жёлтая рамка с именем плейсхолдера и описанием, что сюда вставить."""
    box = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    box.adjustments[0] = 0.04
    box.shadow.inherit = False
    box.fill.solid()
    box.fill.fore_color.rgb = WARN_FILL
    box.line.color.rgb = WARN_LINE
    box.line.width = Pt(1.5)
    tf = box.text_frame
    tf.word_wrap, tf.vertical_anchor = True, MSO_ANCHOR.MIDDLE
    par = tf.paragraphs[0]
    par.alignment = PP_ALIGN.CENTER
    _run(par, "{{" + key + "}}", 16, bold=True, color=WARN_LINE)
    par = tf.add_paragraph()
    par.alignment = PP_ALIGN.CENTER
    _run(par, what, 12, color=MUTED)


def table(slide, x, y, w, rows, col_widths, size=13, row_h=0.42, bold_rows=()):
    shape = slide.shapes.add_table(len(rows), len(rows[0]), Inches(x), Inches(y), Inches(w), Inches(row_h * len(rows)))
    tbl = shape.table
    total = sum(col_widths)
    for j, cw in enumerate(col_widths):
        tbl.columns[j].width = Inches(w * cw / total)
    for i, row in enumerate(rows):
        tbl.rows[i].height = Inches(row_h)
        for j, val in enumerate(row):
            cell = tbl.cell(i, j)
            cell.fill.solid()
            cell.fill.fore_color.rgb = ACCENT if i == 0 else (SOFT if i % 2 == 0 else WHITE)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            cell.margin_left = cell.margin_right = Inches(0.08)
            cell.margin_top = cell.margin_bottom = Inches(0.03)
            tf = cell.text_frame
            tf.word_wrap = True
            par = tf.paragraphs[0]
            par.alignment = PP_ALIGN.LEFT if j == 0 else PP_ALIGN.CENTER
            is_pending = "{{" in str(val)
            _run(par, str(val), size - 4 if is_pending else size, bold=(i == 0 or i in bold_rows),
                 color=WHITE if i == 0 else (WARN_LINE if is_pending else INK))
    return tbl


def notes(slide, body: str):
    slide.notes_slide.notes_text_frame.text = body.strip()


